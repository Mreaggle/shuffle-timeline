function record(date, text, sourceKeys, { needsReview = false, note } = {}) {
  const keys = Array.isArray(sourceKeys) ? sourceKeys : [sourceKeys];
  return {
    date,
    text,
    sources: keys.map((key) => sourceCatalog[key]),
    ...(needsReview ? { needsReview: true } : {}),
    ...(note ? { note } : {})
  };
}

